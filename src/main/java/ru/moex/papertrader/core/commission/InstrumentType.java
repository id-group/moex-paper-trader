package ru.moex.papertrader.core.commission;

/**
 * Тип инструмента, определяющий схему расчёта комиссии.
 *
 * <p>Коды совпадают с {@code Instrument.type} Мосбиржи/БКС ({@code STOCK}, {@code FUTURES}), чтобы
 * адаптеры могли передавать тип без дополнительного маппинга.
 */
public enum InstrumentType {
  /** Акция: комиссия — процент от оборота, но не меньше минимальной комиссии за сделку. */
  STOCK,

  /** Фьючерс: комиссия — фиксированный биржевой сбор за контракт. */
  FUTURES
}

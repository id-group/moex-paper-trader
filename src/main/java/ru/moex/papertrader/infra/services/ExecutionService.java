package ru.moex.papertrader.infra.services;

import ru.moex.papertrader.core.domain.Order;
import ru.moex.papertrader.core.domain.OrderIdType;

/**
 * Исполнение активных заявок по стакану и обслуживание их жизненного цикла.
 *
 * <p>Заявка исполняется при пересечении рынка: маркет — сразу по доступным уровням, лимит — когда
 * цена стакана становится «лимит или лучше». Каждый проход фиксирует сделки и события в отдельных
 * транзакциях, поэтому сбой одной заявки не откатывает соседние.
 */
public interface ExecutionService {

  /**
   * Пытается исполнить заявку по текущему стакану. Неактивная заявка возвращается без изменений.
   *
   * @return актуальное состояние заявки после матчинга
   */
  Order execute(OrderIdType idType, String orderId);

  /**
   * Один проход планировщика: снимает истёкшие DAY/GTD и пытается исполнить остальные активные
   * заявки в пределах открытой сессии.
   *
   * @return количество обработанных заявок
   */
  int tick();
}

package ru.moex.papertrader.infra.services;

/** Счёт виртуального портфеля: идемпотентное создание и пессимистичная блокировка строки. */
public interface AccountService {

  /** Создаёт счёт и его денежный остаток, если их ещё нет; существующий баланс не трогает. */
  void ensureAccount();

  /**
   * Гарантирует существование счёта и блокирует его строку ({@code SELECT ... FOR UPDATE}) до конца
   * текущей транзакции. Под блокировкой выполняются нумерация заявок и проверка дубликатов.
   */
  void lockAccount(String accountId);
}
